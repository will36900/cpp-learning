#include <iostream>
using namespace std;
// ==================== C++ 原生数组的特点 ====================
// 这里讨论 int arr[5] 这样的原生数组，不是 vector 或 std::array。
//
// 1. 元素类型相同
//    int arr[3] 中的三个元素都是 int，不能分别指定成不同类型。
//    初始化的值可能发生类型转换，但存入数组后仍是数组指定的元素类型。
//
// 2. 元素在内存中连续存放
//    arr[0]、arr[1]、arr[2] 按顺序相邻。
//    相邻元素的地址相差 sizeof(元素类型) 个字节。
//    int 的大小取决于实现，不要假设在所有机器上都占 4 字节。
//
// 3. 长度固定
//    int arr[5] 创建后始终包含 5 个元素，不能直接扩容或缩小。
//    使用了几个元素，与数组实际具有几个元素，是两回事。
//    标准 C++ 的普通数组声明要求长度是编译期常量。
//    输入 n 后声明 int arr[n] 不是标准 C++，部分编译器会作为扩展接受。
//    需要运行时决定长度或增删元素，可以使用 std::vector。
//
// 4. 下标从 0 开始
//    长度为 n 的数组，合法下标是 0 到 n - 1。
//    int arr[3] 的元素是 arr[0]、arr[1]、arr[2]。
//    遍历通常写 i < n，不是 i <= n，后者会多访问一个元素。
//
// 5. 不自动做边界检查
//    对 int arr[3]，arr[3] 和 arr[-1] 的读取或写入都越界。
//    越界属于未定义行为：可能输出乱值、破坏数据、崩溃，或看似正常。
//    没有报错或崩溃，并不能说明代码正确。
//    编译器和调试工具可能发现部分越界，但不能依赖它们发现所有问题。
//    std::array 和 std::vector 的 at() 会检查下标，越界时抛出异常。
//
// 6. 初始化方式决定初始值
//    函数内普通局部数组 int a[3]; 没有初始化，必须先赋值再读取。
//    不能认为这种局部数组的元素默认都是 0。
//    int b[3] = {};       三个元素全部为 0。
//    int c[3] = {10};     元素分别为 10、0、0，剩余元素自动补零。
//    int d[] = {1, 2, 3}; 根据初始值数量推导长度为 3。
//    全局 int 数组和 static int 数组没有显式初始化时，元素会初始化为 0。
//
// 7. 按下标访问的时间复杂度为 O(1)
//    可以通过首元素地址、下标、元素大小直接定位元素。
//    访问 arr[2] 不需要先遍历前两个元素。
//    但是按数值查找元素，通常仍需要遍历，时间复杂度为 O(n)。
//
// 8. 不能直接整体赋值，== 也不逐个比较内容
//    两个已经声明的原生数组 a、b，不能使用 b = a 复制内容。
//    a == b 比较的是转换后的指针，不是对应位置的元素值。
//    复制可用循环或 std::copy，比较内容可用循环或 std::equal。
//    std::array 和 std::vector 则支持赋值和元素内容比较。
//
// 9. 数组不是指针，但很多表达式中会退化为指向首元素的指针
//    函数参数 int arr[] 实际会被调整为 int* arr。
//    因此这种函数参数不会自动携带数组长度，通常要另传长度。
//    数组仍保持数组类型时，sizeof(arr) 是整个数组的字节数。
//    但上述函数参数中 sizeof(arr) 是指针大小，不能用来求数组长度。
//    使用数组引用等其他接口，可以保留长度信息。
//
// 10. 可以修改元素内容，但要区分“位置”和“值”
//     数组本身会在内存中存储各个元素的值，并不是只记录位置。
//     下标用于选择位置：arr[1] 表示第二个元素，而不是查找数值 1。
//     arr[1] = 100 表示把第二个元素存储的旧值替换为 100。
//     普通赋值不会改变这个元素的地址、下标或数组长度。
//     数组不会自动保存旧值的历史，也不会记住某个值原来位于哪里。
//     如果要保留修改前的值，必须自己复制到另一个变量或数组。
//     如果要根据内容寻找位置，需要遍历或使用查找算法。
//     注意：声明为 const 的数组不允许修改元素。

// const 表示函数不通过 arr 修改元素。
// 调用者必须保证 size 不超过真实长度，否则这个循环也会越界。
void print_array(const int arr[], int size)
{
    for (int i = 0; i < size; ++i)
    {
        cout << arr[i] << ' ';
    }
    cout << endl;
}

int main()
{
    int arr[] = {10, 20, 30}; // 编译器推导长度为 3。

    // 总字节数除以一个元素的字节数，得到元素数量。
    // 只适用于真正的数组，不能用于已经退化为指针的函数参数。
    const int size = sizeof(arr) / sizeof(arr[0]);
    cout << "数组长度：" << size << endl;
    cout << "首元素：" << arr[0] << endl;
    cout << "末元素：" << arr[size - 1] << endl;

    // 保存第二个元素修改前的值，以及它在内存中的地址。
    // old_value 是一份独立的值的副本，后续修改 arr[1] 不会改变它。
    // element_address 指向数组中的第二个元素，不是保存它的旧值。
    int old_value = arr[1];
    int* element_address = &arr[1];
    cout << "修改前第二个元素的值：" << arr[1] << endl;
    cout << "修改前第二个元素的地址："
         << static_cast<const void*>(element_address) << endl;

    arr[1] = 100; // 把第二个位置上的 20 替换为 100，长度仍为 3。
    cout << "修改后：";
    print_array(arr, size);
    cout << "修改后第二个元素的地址："
         << static_cast<const void*>(&arr[1]) << endl;
    cout << "单独保存的旧值：" << old_value << endl; // 仍然是 20。
    cout << "通过原来的地址读取当前值：" << *element_address << endl; // 100。

    // 两次输出的地址相同：变化的是这个位置存储的值。
    // *element_address 表示读取该指针所指向的元素，所以会读到修改后的值。
    // 若要把值为 30 的元素改成 300，应先查找，再修改找到的位置。
    // 不能写 arr[30] = 300，那会把 30 当成下标，导致当前数组越界。
    for (int i = 0; i < size; ++i)
    {
        if (arr[i] == 30)
        {
            arr[i] = 300;
            break; // 这里只修改第一个匹配项；删除 break 可修改所有匹配项。
        }
    }
    cout << "把值为 30 的首个元素改为 300 后：";
    print_array(arr, size);

    // 以下代码越界，只作为反例保留，不要取消注释运行。
    // cout << arr[3]; // 最大合法下标是 2。
    // arr[-1] = 99;  // 负下标同样越界。

    int zeros[3] = {};     // 0、0、0。
    int partial[3] = {10}; // 10、0、0。
    cout << "全部初始化为零：";
    print_array(zeros, 3);
    cout << "部分初始化：";
    print_array(partial, 3);

    int copied[3] = {};
    // copied = arr; // 错误：原生数组不能直接整体赋值。
    for (int i = 0; i < size; ++i)
    {
        copied[i] = arr[i]; // 每次复制一个元素。
    }
    cout << "复制后：";
    print_array(copied, size);

    return 0;
}
