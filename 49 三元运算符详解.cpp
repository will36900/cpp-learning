#include <iostream>
using namespace std;

/*
 * ==========================================
 *     三元运算符详解 (? :)
 * ==========================================
 *
 * 格式：条件 ? 值1 : 值2
 *
 * 意思：如果条件为真，返回值1，否则返回值2
 */

int main() {
    cout << "==========================================" << endl;
    cout << "    三元运算符 (? :) 详解" << endl;
    cout << "==========================================" << endl;

    // ==========================================
    // 1. 基本语法
    // ==========================================
    cout << "\n【1. 基本语法】" << endl;
    cout << "-----------------------------------" << endl;

    int age = 20;

    // 三元运算符写法
    string result = (age >= 18) ? "成年人" : "未成年人";
    cout << "年龄：" << age << "，身份：" << result << endl;

    // 等价的 if-else 写法
    string result2;
    if (age >= 18) {
        result2 = "成年人";
    } else {
        result2 = "未成年人";
    }
    cout << "用if-else：" << result2 << endl;

    cout << "\n💡 三元运算符是 if-else 的简写形式！" << endl;

    // ==========================================
    // 2. 结构分析
    // ==========================================
    cout << "\n【2. 结构分析】" << endl;
    cout << "-----------------------------------" << endl;
    cout << "格式：条件 ? 值1 : 值2" << endl;
    cout << "      ↓    ↓  ↓   ↓  ↓" << endl;
    cout << "   判断  问号 真  冒号 假" << endl;

    int num = 8;
    cout << "\n例子：(num % 2 == 0) ? \"偶数\" : \"奇数\"" << endl;
    cout << "      ↓             ↓      ↓" << endl;
    cout << "   判断是否为偶数   是偶数   不是偶数" << endl;
    cout << "\n结果：" << num << " 是 " << ((num % 2 == 0) ? "偶数" : "奇数") << endl;

    // ==========================================
    // 3. 常见用法
    // ==========================================
    cout << "\n【3. 常见用法】" << endl;
    cout << "-----------------------------------" << endl;

    // 用法1：判断大小
    int a = 10, b = 20;
    int max = (a > b) ? a : b;
    cout << "max(" << a << ", " << b << ") = " << max << endl;

    // 用法2：判断正负
    int x = -5;
    string sign = (x >= 0) ? "正数或零" : "负数";
    cout << x << " 是 " << sign << endl;

    // 用法3：输出不同文本
    int score = 85;
    cout << "成绩：" << score << "，结果："
         << (score >= 60 ? "及格" : "不及格") << endl;

    // 用法4：计算不同值
    int n = 5;
    int abs_n = (n >= 0) ? n : -n;  // 求绝对值
    cout << n << " 的绝对值 = " << abs_n << endl;

    // ==========================================
    // 4. 嵌套使用（多个条件）
    // ==========================================
    cout << "\n【4. 嵌套使用】" << endl;
    cout << "-----------------------------------" << endl;

    int grade = 75;
    string level = (grade >= 90) ? "优秀" :
                   (grade >= 80) ? "良好" :
                   (grade >= 60) ? "及格" : "不及格";
    cout << "分数：" << grade << "，等级：" << level << endl;

    cout << "\n解析：" << endl;
    cout << "grade >= 90 ? \"优秀\" : (继续判断)" << endl;
    cout << "grade >= 80 ? \"良好\" : (继续判断)" << endl;
    cout << "grade >= 60 ? \"及格\" : \"不及格\"" << endl;

    // ==========================================
    // 5. 直接用在输出中
    // ==========================================
    cout << "\n【5. 直接用在 cout 中】" << endl;
    cout << "-----------------------------------" << endl;

    int num1 = 8, num2 = 7;
    cout << num1 << " 是" << (num1 % 2 == 0 ? "偶数" : "奇数") << endl;
    cout << num2 << " 是" << (num2 % 2 == 0 ? "偶数" : "奇数") << endl;

    bool isPrime = true;
    cout << "17 是质数吗？" << (isPrime ? "是" : "否") << endl;

    // ==========================================
    // 6. 对比 if-else
    // ==========================================
    cout << "\n【6. 三元运算符 vs if-else】" << endl;
    cout << "-----------------------------------" << endl;

    int number = 10;

    cout << "\n写法1：三元运算符（简洁）" << endl;
    cout << number << " 是" << (number > 0 ? "正数" : "非正数") << endl;

    cout << "\n写法2：if-else（清晰）" << endl;
    if (number > 0) {
        cout << number << " 是正数" << endl;
    } else {
        cout << number << " 是非正数" << endl;
    }

    // ==========================================
    // 7. 实战例子
    // ==========================================
    cout << "\n【7. 实战例子】" << endl;
    cout << "-----------------------------------" << endl;

    // 例子1：找最大值
    int p = 5, q = 8, r = 3;
    int maximum = (p > q) ? ((p > r) ? p : r) : ((q > r) ? q : r);
    cout << "max(" << p << ", " << q << ", " << r << ") = " << maximum << endl;

    // 例子2：奇偶性
    for (int i = 1; i <= 5; i++) {
        cout << i << " 是" << (i % 2 == 0 ? "偶数" : "奇数") << endl;
    }

    // 例子3：单复数
    int count = 1;
    cout << count << " apple" << (count > 1 ? "s" : "") << endl;
    count = 3;
    cout << count << " apple" << (count > 1 ? "s" : "") << endl;

    // ==========================================
    // 8. 何时使用？
    // ==========================================
    cout << "\n【8. 何时使用三元运算符？】" << endl;
    cout << "-----------------------------------" << endl;
    cout << "✅ 适合用三元运算符：" << endl;
    cout << "   • 简单的二选一" << endl;
    cout << "   • 直接赋值或输出" << endl;
    cout << "   • 一行能写完" << endl;
    cout << "" << endl;
    cout << "❌ 不适合用三元运算符：" << endl;
    cout << "   • 逻辑复杂，需要多条语句" << endl;
    cout << "   • 嵌套太多，难以阅读" << endl;
    cout << "   • 需要执行函数调用" << endl;

    // ==========================================
    // 9. 常见错误
    // ==========================================
    cout << "\n【9. 常见错误】" << endl;
    cout << "-----------------------------------" << endl;

    cout << "\n❌ 错误1：忘记括号" << endl;
    cout << "错误：cout << isEven(8) ? \"是\" : \"否\";" << endl;
    cout << "正确：cout << (isEven(8) ? \"是\" : \"否\");" << endl;
    cout << "原因：? : 运算符优先级低于 <<" << endl;

    cout << "\n❌ 错误2：类型不匹配" << endl;
    cout << "错误：int x = (a > b) ? 10 : \"错误\";  // 一个int，一个string" << endl;
    cout << "正确：int x = (a > b) ? 10 : -1;" << endl;

    cout << "\n❌ 错误3：嵌套太多" << endl;
    cout << "难读：x = a?b?c?d:e:f:g?h:i;" << endl;
    cout << "建议：用 if-else 或多个变量拆开" << endl;

    // ==========================================
    // 总结
    // ==========================================
    cout << "\n==========================================" << endl;
    cout << "📌 核心要点" << endl;
    cout << "==========================================" << endl;
    cout << "1. 格式：条件 ? 真值 : 假值" << endl;
    cout << "2. 作用：简化简单的 if-else" << endl;
    cout << "3. 等价：" << endl;
    cout << "   x = (a > b) ? a : b;" << endl;
    cout << "   等于" << endl;
    cout << "   if (a > b) x = a; else x = b;" << endl;
    cout << "4. 记忆：用问号(?)提问，用冒号(:)分隔答案" << endl;
    cout << "==========================================" << endl;

    return 0;
}

